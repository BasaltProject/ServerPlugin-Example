package org.basaltmc.server.example.entities


import org.basaltmc.server.core.Ctx

object EntitiesExample {
    private fun tour(ctx: Ctx) {
        val player = org.basaltmc.server.players.playerByName(org.basaltmc.server.commands.commandSourceName(ctx) ?: "")
        val me = org.basaltmc.server.entities.entityOfPlayer(player)
        org.basaltmc.server.entities.entityPlayer(me)
        org.basaltmc.server.entities.entityAlive(me)
        org.basaltmc.server.entities.entityId(me)
        val buf1 = DoubleArray(3)
        org.basaltmc.server.entities.entityPosition(me, buf1)
        val spec2 = org.basaltmc.server.values.ValueWriter().beginMap().key("yaw").float(90.0).key("pitch").float(10.0).end().finish() ?: ByteArray(0)
        org.basaltmc.server.entities.entityTeleport(me, 10.5, 64.0, -3.5, spec2)
        val spec3 = org.basaltmc.server.values.ValueWriter().beginMap().key("world").string("nowhere").end().finish() ?: ByteArray(0)
        org.basaltmc.server.entities.entityTeleport(me, 1.0, 2.0, 3.0, spec3)
        val buf4 = DoubleArray(2)
        org.basaltmc.server.entities.entityRotation(me, buf4)
        org.basaltmc.server.entities.entitySetRotation(me, 45.0, 5.0)
        val buf5 = ByteArray(256)
        org.basaltmc.server.entities.entityGet(me, "x", buf5)
        val buf6 = ByteArray(256)
        org.basaltmc.server.entities.entityGet(me, "nope", buf6)
        val buf7 = ByteArray(256)
        org.basaltmc.server.entities.entityGet(me, "uuid", buf7)
        val buf8 = ByteArray(1024)
        org.basaltmc.server.entities.entityProperties(me, buf8)
        val buf9 = ByteArray(1024)
        org.basaltmc.server.entities.entityOperations(me, buf9)
        val buf10 = ByteArray(2048)
        org.basaltmc.server.entities.entityTypes(buf10)
        val buf11 = ByteArray(512)
        org.basaltmc.server.entities.entityTypeAttributes("minecraft:pig", buf11)
        val buf12 = ByteArray(512)
        org.basaltmc.server.entities.entityTypeAttributes("minecraft:nothing", buf12)
        val spec13 = org.basaltmc.server.values.ValueWriter().beginMap().key("yaw").float(90.0).end().finish() ?: ByteArray(0)
        val pig = org.basaltmc.server.entities.entitySpawn("world", "minecraft:pig", 1.0, 64.0, 2.0, spec13)
        org.basaltmc.server.entities.entitySpawn("world", "minecraft:nothing", 0.0, 0.0, 0.0, ByteArray(0))
        val zombie = org.basaltmc.server.entities.entitySpawn("world", "minecraft:zombie", 3.0, 64.0, 2.0, ByteArray(0))
        val spec14 = org.basaltmc.server.values.ValueWriter().beginMap().key("reason").string("veto").end().finish() ?: ByteArray(0)
        org.basaltmc.server.entities.entitySpawn("world", "minecraft:pig", 0.0, 0.0, 0.0, spec14)
        org.basaltmc.server.entities.entitySpawn("nowhere", "minecraft:pig", 0.0, 0.0, 0.0, ByteArray(0))
        val pig_id = org.basaltmc.server.entities.entityId(pig)
        org.basaltmc.server.entities.entityById("world", pig_id)
        org.basaltmc.server.entities.entityById("world", 9999)
        org.basaltmc.server.entities.entityByUuid("00000000-0000-4000-8000-000000000001")
        org.basaltmc.server.entities.entityByUuid("not-a-uuid")
        val spec15 = org.basaltmc.server.values.ValueWriter().beginMap().key("type").string("minecraft:pig").end().finish() ?: ByteArray(0)
        val buf16 = IntArray(8)
        org.basaltmc.server.entities.entityQuery("world", spec15, buf16)
        val spec17 = org.basaltmc.server.values.ValueWriter().beginMap().key("x").float(1.0).key("y").float(64.0).key("z").float(2.0).key("radius").float(5.0).key("limit").int(10L).end().finish() ?: ByteArray(0)
        val buf18 = IntArray(8)
        org.basaltmc.server.entities.entityQuery("world", spec17, buf18)
        org.basaltmc.server.entities.entitySetVelocity(pig, 0.0, 0.5, 0.0)
        val buf19 = DoubleArray(3)
        org.basaltmc.server.entities.entityVelocity(pig, buf19)
        val buf20 = DoubleArray(3)
        org.basaltmc.server.entities.entityVelocity(me, buf20)
        val spec21 = org.basaltmc.server.values.ValueWriter().bool(true).finish() ?: ByteArray(0)
        org.basaltmc.server.entities.entitySet(pig, "glowing", spec21)
        val buf22 = ByteArray(64)
        org.basaltmc.server.entities.entityGet(pig, "glowing", buf22)
        val spec23 = org.basaltmc.server.values.ValueWriter().int(1L).finish() ?: ByteArray(0)
        org.basaltmc.server.entities.entitySet(pig, "vehicle", spec23)
        val spec24 = org.basaltmc.server.values.ValueWriter().bool(true).finish() ?: ByteArray(0)
        org.basaltmc.server.entities.entitySet(pig, "nope", spec24)
        val spec25 = org.basaltmc.server.values.ValueWriter().beginList().float(3.0).end().finish() ?: ByteArray(0)
        val buf26 = ByteArray(64)
        org.basaltmc.server.entities.entityCall(pig, "damage", spec25, buf26)
        val spec27 = org.basaltmc.server.values.ValueWriter().beginList().string("minecraft:speed").int(200L).int(1L).end().finish() ?: ByteArray(0)
        val buf28 = ByteArray(64)
        org.basaltmc.server.entities.entityCall(pig, "add_effect", spec27, buf28)
        val buf29 = ByteArray(512)
        org.basaltmc.server.entities.entityCall(pig, "effects", ByteArray(0), buf29)
        val spec30 = org.basaltmc.server.values.ValueWriter().beginList().string("example:wander").int(3L).string("MOVE").end().finish() ?: ByteArray(0)
        val buf31 = ByteArray(64)
        org.basaltmc.server.entities.entityCall(pig, "add_goal", spec30, buf31)
        val spec32 = org.basaltmc.server.values.ValueWriter().beginList().string("example:wander").end().finish() ?: ByteArray(0)
        val buf33 = ByteArray(64)
        org.basaltmc.server.entities.entityCall(pig, "has_goal", spec32, buf33)
        val buf34 = ByteArray(512)
        org.basaltmc.server.entities.entityCall(pig, "goals", ByteArray(0), buf34)
        val spec35 = org.basaltmc.server.values.ValueWriter().beginList().float(5.0).float(64.0).float(5.0).end().finish() ?: ByteArray(0)
        val buf36 = ByteArray(512)
        org.basaltmc.server.entities.entityCall(pig, "find_path", spec35, buf36)
        val buf37 = ByteArray(64)
        org.basaltmc.server.entities.entityCall(pig, "bogus", ByteArray(0), buf37)
        val snap = ByteArray(4096)
        val saved = org.basaltmc.server.entities.entitySnapshot(pig, snap)
        org.basaltmc.server.entities.entityRestore(pig, snap.copyOf(saved))
        val clone = org.basaltmc.server.entities.entitySpawnNbt("world", snap.copyOf(saved), "command")
        val spec39 = org.basaltmc.server.values.ValueWriter().beginMap().key("id").string("minecraft:diamond").key("count").int(2L).end().finish() ?: ByteArray(0)
        val drop = org.basaltmc.server.entities.entityDropItem("world", spec39, 1.0, 65.0, 2.0, 0.0, 0.2, 0.0)
        val spec40 = org.basaltmc.server.values.ValueWriter().beginMap().key("count").int(1L).end().finish() ?: ByteArray(0)
        org.basaltmc.server.entities.entityDropItem("world", spec40, 1.0, 65.0, 2.0, 0.0, 0.0, 0.0)
        val spec41 = org.basaltmc.server.values.ValueWriter().beginMap().key("limits").beginMap().key("monster").int(20L).end().key("allow_animals").bool(false).end().finish() ?: ByteArray(0)
        val buf42 = ByteArray(512)
        org.basaltmc.server.entities.entitySpawnRules("world", spec41, buf42)
        val spec43 = org.basaltmc.server.values.ValueWriter().beginMap().key("limits").beginMap().key("monster").int(-1L).end().key("allow_animals").bool(true).end().finish() ?: ByteArray(0)
        val buf44 = ByteArray(512)
        org.basaltmc.server.entities.entitySpawnRules("world", spec43, buf44)
        val spec45 = org.basaltmc.server.values.ValueWriter().beginMap().key("distance").float(10.0).end().finish() ?: ByteArray(0)
        val buf46 = ByteArray(64)
        org.basaltmc.server.entities.entityMechanic("combat.fall_damage", spec45, buf46)
        val spec47 = org.basaltmc.server.values.ValueWriter().beginMap().key("tick_count").float(10.0).end().finish() ?: ByteArray(0)
        val buf48 = ByteArray(64)
        org.basaltmc.server.entities.entityMechanic("physics.projectile_margin", spec47, buf48)
        val spec49 = org.basaltmc.server.values.ValueWriter().beginMap().end().finish() ?: ByteArray(0)
        val buf50 = ByteArray(64)
        org.basaltmc.server.entities.entityMechanic("nope", spec49, buf50)
        org.basaltmc.server.entities.entityRemove(pig)
        org.basaltmc.server.entities.entityAlive(pig)
        val buf51 = DoubleArray(3)
        org.basaltmc.server.entities.entityPosition(pig, buf51)
        org.basaltmc.server.entities.entityRemove(pig)
        org.basaltmc.server.entities.entityRemoveUuid("world", "00000000-0000-4000-8000-0000000000ff")
        org.basaltmc.server.entities.entityRemoveUuid("world", "nope")
        org.basaltmc.server.entities.entityRemove(zombie)
        org.basaltmc.server.entities.entityRemove(clone)
        org.basaltmc.server.entities.entityRemove(drop)
        org.basaltmc.server.entities.entityRelease(me)
        org.basaltmc.server.entities.entityRelease(me)
        org.basaltmc.server.commands.commandReply(ctx, "tour done")
    }

    private fun bad(ctx: Ctx) {
        org.basaltmc.server.entities.entityAlive(999)
        org.basaltmc.server.entities.entityId(0)
        org.basaltmc.server.entities.entityPlayer(-5)
        org.basaltmc.server.entities.entityByUuid("")
        org.basaltmc.server.entities.entityEventEntity(ctx)
        org.basaltmc.server.entities.entityAiAnswer(ctx, 1)
        val buf1 = DoubleArray(3)
        org.basaltmc.server.entities.entityPosition(7, buf1)
        val spec2 = org.basaltmc.server.values.ValueWriter().beginMap().end().finish() ?: ByteArray(0)
        val buf3 = ByteArray(16)
        org.basaltmc.server.entities.entityMechanic("", spec2, buf3)
        org.basaltmc.server.commands.commandReply(ctx, "bad done")
    }

    fun register() {
        org.basaltmc.server.commands.command("entities tour", "", ::tour)
        org.basaltmc.server.commands.command("entities bad", "", ::bad)
    }
}
