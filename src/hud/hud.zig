fn entityOf(npc: i32) i32 {
    var raw: [768]u8 = undefined;
    const length = basalt.hud.npcGet(npc, &raw);
    if (length <= 0 or length > raw.len) return 0;
    const value = basalt.values.Value.open(raw[0..@intCast(length)]) orelse return 0;
    const id = value.find("id") orelse return 0;
    return @intCast(id.asInt() orelse 0);
}

