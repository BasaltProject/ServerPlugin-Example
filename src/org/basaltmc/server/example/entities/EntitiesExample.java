package org.basaltmc.server.example.entities;

import static org.basaltmc.server.commands.Commands.command;
import static org.basaltmc.server.commands.Commands.commandReply;
import static org.basaltmc.server.commands.Commands.commandSourceName;
import static org.basaltmc.server.players.SharedPlayers.playerByName;
import org.basaltmc.server.entities.Entities;
import org.basaltmc.server.values.Values;

public final class EntitiesExample {
    private EntitiesExample() {}

    private static void tour(int ctx) {
        int player = playerByName(commandSourceName(ctx));
        int me = Entities.ofPlayer(player);
        Entities.player(me);
        Entities.alive(me);
        Entities.id(me);
        double[] buf1 = new double[3];
        Entities.position(me, buf1);
        byte[] spec2 = new Values.Writer().beginMap().key("yaw").number(90.0).key("pitch").number(10.0).end().finish();
        Entities.teleport(me, 10.5, 64.0, -3.5, spec2);
        byte[] spec3 = new Values.Writer().beginMap().key("world").string("nowhere").end().finish();
        Entities.teleport(me, 1.0, 2.0, 3.0, spec3);
        double[] buf4 = new double[2];
        Entities.rotation(me, buf4);
        Entities.setRotation(me, 45.0, 5.0);
        byte[] buf5 = new byte[256];
        Entities.get(me, "x", buf5);
        byte[] buf6 = new byte[256];
        Entities.get(me, "nope", buf6);
        byte[] buf7 = new byte[256];
        Entities.get(me, "uuid", buf7);
        byte[] buf8 = new byte[1024];
        Entities.properties(me, buf8);
        byte[] buf9 = new byte[1024];
        Entities.operations(me, buf9);
        byte[] buf10 = new byte[2048];
        Entities.types(buf10);
        byte[] buf11 = new byte[512];
        Entities.typeAttributes("minecraft:pig", buf11);
        byte[] buf12 = new byte[512];
        Entities.typeAttributes("minecraft:nothing", buf12);
        byte[] spec13 = new Values.Writer().beginMap().key("yaw").number(90.0).end().finish();
        int pig = Entities.spawn("world", "minecraft:pig", 1.0, 64.0, 2.0, spec13);
        Entities.spawn("world", "minecraft:nothing", 0.0, 0.0, 0.0, new byte[0]);
        int zombie = Entities.spawn("world", "minecraft:zombie", 3.0, 64.0, 2.0, new byte[0]);
        byte[] spec14 = new Values.Writer().beginMap().key("reason").string("veto").end().finish();
        Entities.spawn("world", "minecraft:pig", 0.0, 0.0, 0.0, spec14);
        Entities.spawn("nowhere", "minecraft:pig", 0.0, 0.0, 0.0, new byte[0]);
        int pig_id = Entities.id(pig);
        Entities.byId("world", pig_id);
        Entities.byId("world", 9999);
        Entities.byUuid("00000000-0000-4000-8000-000000000001");
        Entities.byUuid("not-a-uuid");
        byte[] spec15 = new Values.Writer().beginMap().key("type").string("minecraft:pig").end().finish();
        int[] buf16 = new int[8];
        Entities.query("world", spec15, buf16);
        byte[] spec17 = new Values.Writer().beginMap().key("x").number(1.0).key("y").number(64.0).key("z").number(2.0).key("radius").number(5.0).key("limit").integer(10L).end().finish();
        int[] buf18 = new int[8];
        Entities.query("world", spec17, buf18);
        Entities.setVelocity(pig, 0.0, 0.5, 0.0);
        double[] buf19 = new double[3];
        Entities.velocity(pig, buf19);
        double[] buf20 = new double[3];
        Entities.velocity(me, buf20);
        byte[] spec21 = new Values.Writer().bool(true).finish();
        Entities.set(pig, "glowing", spec21);
        byte[] buf22 = new byte[64];
        Entities.get(pig, "glowing", buf22);
        byte[] spec23 = new Values.Writer().integer(1L).finish();
        Entities.set(pig, "vehicle", spec23);
        byte[] spec24 = new Values.Writer().bool(true).finish();
        Entities.set(pig, "nope", spec24);
        byte[] spec25 = new Values.Writer().beginList().number(3.0).end().finish();
        byte[] buf26 = new byte[64];
        Entities.call(pig, "damage", spec25, buf26);
        byte[] spec27 = new Values.Writer().beginList().string("minecraft:speed").integer(200L).integer(1L).end().finish();
        byte[] buf28 = new byte[64];
        Entities.call(pig, "add_effect", spec27, buf28);
        byte[] buf29 = new byte[512];
        Entities.call(pig, "effects", new byte[0], buf29);
        byte[] spec30 = new Values.Writer().beginList().string("example:wander").integer(3L).string("MOVE").end().finish();
        byte[] buf31 = new byte[64];
        Entities.call(pig, "add_goal", spec30, buf31);
        byte[] spec32 = new Values.Writer().beginList().string("example:wander").end().finish();
        byte[] buf33 = new byte[64];
        Entities.call(pig, "has_goal", spec32, buf33);
        byte[] buf34 = new byte[512];
        Entities.call(pig, "goals", new byte[0], buf34);
        byte[] spec35 = new Values.Writer().beginList().number(5.0).number(64.0).number(5.0).end().finish();
        byte[] buf36 = new byte[512];
        Entities.call(pig, "find_path", spec35, buf36);
        byte[] buf37 = new byte[64];
        Entities.call(pig, "bogus", new byte[0], buf37);
        byte[] snap = new byte[4096];
        int saved = Entities.snapshot(pig, snap);
        Entities.restore(pig, java.util.Arrays.copyOf(snap, saved));
        int clone = Entities.spawnNbt("world", java.util.Arrays.copyOf(snap, saved), "command");
        byte[] spec39 = new Values.Writer().beginMap().key("id").string("minecraft:diamond").key("count").integer(2L).end().finish();
        int drop = Entities.dropItem("world", spec39, 1.0, 65.0, 2.0, 0.0, 0.2, 0.0);
        byte[] spec40 = new Values.Writer().beginMap().key("count").integer(1L).end().finish();
        Entities.dropItem("world", spec40, 1.0, 65.0, 2.0, 0.0, 0.0, 0.0);
        byte[] spec41 = new Values.Writer().beginMap().key("limits").beginMap().key("monster").integer(20L).end().key("allow_animals").bool(false).end().finish();
        byte[] buf42 = new byte[512];
        Entities.spawnRules("world", spec41, buf42);
        byte[] spec43 = new Values.Writer().beginMap().key("limits").beginMap().key("monster").integer(-1L).end().key("allow_animals").bool(true).end().finish();
        byte[] buf44 = new byte[512];
        Entities.spawnRules("world", spec43, buf44);
        byte[] spec45 = new Values.Writer().beginMap().key("distance").number(10.0).end().finish();
        byte[] buf46 = new byte[64];
        Entities.mechanic("combat.fall_damage", spec45, buf46);
        byte[] spec47 = new Values.Writer().beginMap().key("tick_count").number(10.0).end().finish();
        byte[] buf48 = new byte[64];
        Entities.mechanic("physics.projectile_margin", spec47, buf48);
        byte[] spec49 = new Values.Writer().beginMap().end().finish();
        byte[] buf50 = new byte[64];
        Entities.mechanic("nope", spec49, buf50);
        Entities.remove(pig);
        Entities.alive(pig);
        double[] buf51 = new double[3];
        Entities.position(pig, buf51);
        Entities.remove(pig);
        Entities.removeUuid("world", "00000000-0000-4000-8000-0000000000ff");
        Entities.removeUuid("world", "nope");
        Entities.remove(zombie);
        Entities.remove(clone);
        Entities.remove(drop);
        Entities.release(me);
        Entities.release(me);
        commandReply(ctx, "tour done");
    }

    private static void bad(int ctx) {
        Entities.alive(999);
        Entities.id(0);
        Entities.player(-5);
        Entities.byUuid("");
        Entities.eventEntity(ctx);
        Entities.aiAnswer(ctx, 1);
        double[] buf1 = new double[3];
        Entities.position(7, buf1);
        byte[] spec2 = new Values.Writer().beginMap().end().finish();
        byte[] buf3 = new byte[16];
        Entities.mechanic("", spec2, buf3);
        commandReply(ctx, "bad done");
    }

    public static void register() {
        command("entities tour", "", EntitiesExample::tour);
        command("entities bad", "", EntitiesExample::bad);
    }
}
