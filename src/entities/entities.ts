import * as bsCommands from "basalt-server/commands";
import * as bsCore from "basalt-server/core";
import * as bsEntities from "basalt-server/entities";
import * as bsPlayers from "basalt-server/players";
import * as bsValues from "basalt-server/values";

function tour(ctx: bsCore.Ctx): void {
  const player = bsPlayers.playerByName(bsCommands.commandSourceName(ctx)!);
  const me = bsEntities.entityOfPlayer(player);
  bsEntities.entityPlayer(me);
  bsEntities.entityAlive(me);
  bsEntities.entityId(me);
  const buf1 = new Float64Array(3);
  bsEntities.entityPosition(me, buf1);
  const spec2 = new bsValues.ValueWriter().beginMap().key("yaw").float(90.0).key("pitch").float(10.0).end().finish()!;
  bsEntities.entityTeleport(me, 10.5, 64.0, -3.5, spec2);
  const spec3 = new bsValues.ValueWriter().beginMap().key("world").string("nowhere").end().finish()!;
  bsEntities.entityTeleport(me, 1.0, 2.0, 3.0, spec3);
  const buf4 = new Float64Array(2);
  bsEntities.entityRotation(me, buf4);
  bsEntities.entitySetRotation(me, 45.0, 5.0);
  const buf5 = new Uint8Array(256);
  bsEntities.entityGet(me, "x", buf5);
  const buf6 = new Uint8Array(256);
  bsEntities.entityGet(me, "nope", buf6);
  const buf7 = new Uint8Array(256);
  bsEntities.entityGet(me, "uuid", buf7);
  const buf8 = new Uint8Array(1024);
  bsEntities.entityProperties(me, buf8);
  const buf9 = new Uint8Array(1024);
  bsEntities.entityOperations(me, buf9);
  const buf10 = new Uint8Array(2048);
  bsEntities.entityTypes(buf10);
  const buf11 = new Uint8Array(512);
  bsEntities.entityTypeAttributes("minecraft:pig", buf11);
  const buf12 = new Uint8Array(512);
  bsEntities.entityTypeAttributes("minecraft:nothing", buf12);
  const spec13 = new bsValues.ValueWriter().beginMap().key("yaw").float(90.0).end().finish()!;
  const pig = bsEntities.entitySpawn("world", "minecraft:pig", 1.0, 64.0, 2.0, spec13);
  bsEntities.entitySpawn("world", "minecraft:nothing", 0.0, 0.0, 0.0, new Uint8Array(0));
  const zombie = bsEntities.entitySpawn("world", "minecraft:zombie", 3.0, 64.0, 2.0, new Uint8Array(0));
  const spec14 = new bsValues.ValueWriter().beginMap().key("reason").string("veto").end().finish()!;
  bsEntities.entitySpawn("world", "minecraft:pig", 0.0, 0.0, 0.0, spec14);
  bsEntities.entitySpawn("nowhere", "minecraft:pig", 0.0, 0.0, 0.0, new Uint8Array(0));
  const pig_id = bsEntities.entityId(pig);
  bsEntities.entityById("world", pig_id);
  bsEntities.entityById("world", 9999);
  bsEntities.entityByUuid("00000000-0000-4000-8000-000000000001");
  bsEntities.entityByUuid("not-a-uuid");
  const spec15 = new bsValues.ValueWriter().beginMap().key("type").string("minecraft:pig").end().finish()!;
  const buf16 = new Int32Array(8);
  bsEntities.entityQuery("world", spec15, buf16);
  const spec17 = new bsValues.ValueWriter().beginMap().key("x").float(1.0).key("y").float(64.0).key("z").float(2.0).key("radius").float(5.0).key("limit").int(10).end().finish()!;
  const buf18 = new Int32Array(8);
  bsEntities.entityQuery("world", spec17, buf18);
  bsEntities.entitySetVelocity(pig, 0.0, 0.5, 0.0);
  const buf19 = new Float64Array(3);
  bsEntities.entityVelocity(pig, buf19);
  const buf20 = new Float64Array(3);
  bsEntities.entityVelocity(me, buf20);
  const spec21 = new bsValues.ValueWriter().boolean(true).finish()!;
  bsEntities.entitySet(pig, "glowing", spec21);
  const buf22 = new Uint8Array(64);
  bsEntities.entityGet(pig, "glowing", buf22);
  const spec23 = new bsValues.ValueWriter().int(1).finish()!;
  bsEntities.entitySet(pig, "vehicle", spec23);
  const spec24 = new bsValues.ValueWriter().boolean(true).finish()!;
  bsEntities.entitySet(pig, "nope", spec24);
  const spec25 = new bsValues.ValueWriter().beginList().float(3.0).end().finish()!;
  const buf26 = new Uint8Array(64);
  bsEntities.entityCall(pig, "damage", spec25, buf26);
  const spec27 = new bsValues.ValueWriter().beginList().string("minecraft:speed").int(200).int(1).end().finish()!;
  const buf28 = new Uint8Array(64);
  bsEntities.entityCall(pig, "add_effect", spec27, buf28);
  const buf29 = new Uint8Array(512);
  bsEntities.entityCall(pig, "effects", new Uint8Array(0), buf29);
  const spec30 = new bsValues.ValueWriter().beginList().string("example:wander").int(3).string("move").end().finish()!;
  const buf31 = new Uint8Array(64);
  bsEntities.entityCall(pig, "add_goal", spec30, buf31);
  const spec32 = new bsValues.ValueWriter().beginList().string("example:wander").end().finish()!;
  const buf33 = new Uint8Array(64);
  bsEntities.entityCall(pig, "has_goal", spec32, buf33);
  const buf34 = new Uint8Array(512);
  bsEntities.entityCall(pig, "goals", new Uint8Array(0), buf34);
  const spec35 = new bsValues.ValueWriter().beginList().float(5.0).float(64.0).float(5.0).end().finish()!;
  const buf36 = new Uint8Array(512);
  bsEntities.entityCall(pig, "find_path", spec35, buf36);
  const buf37 = new Uint8Array(64);
  bsEntities.entityCall(pig, "bogus", new Uint8Array(0), buf37);
  const snap = new Uint8Array(4096);
  const saved = bsEntities.entitySnapshot(pig, snap);
  bsEntities.entityRestore(pig, snap.slice(0, saved));
  const clone = bsEntities.entitySpawnNbt("world", snap.slice(0, saved), "command");
  const spec39 = new bsValues.ValueWriter().beginMap().key("id").string("minecraft:diamond").key("count").int(2).end().finish()!;
  const drop = bsEntities.entityDropItem("world", spec39, 1.0, 65.0, 2.0, 0.0, 0.2, 0.0);
  const spec40 = new bsValues.ValueWriter().beginMap().key("count").int(1).end().finish()!;
  bsEntities.entityDropItem("world", spec40, 1.0, 65.0, 2.0, 0.0, 0.0, 0.0);
  const spec41 = new bsValues.ValueWriter().beginMap().key("limits").beginMap().key("monster").int(20).end().key("allow_animals").boolean(false).end().finish()!;
  const buf42 = new Uint8Array(512);
  bsEntities.entitySpawnRules("world", spec41, buf42);
  const spec43 = new bsValues.ValueWriter().beginMap().key("limits").beginMap().key("monster").int(-1).end().key("allow_animals").boolean(true).end().finish()!;
  const buf44 = new Uint8Array(512);
  bsEntities.entitySpawnRules("world", spec43, buf44);
  const spec45 = new bsValues.ValueWriter().beginMap().key("distance").float(10.0).end().finish()!;
  const buf46 = new Uint8Array(64);
  bsEntities.entityMechanic("combat.fall_damage", spec45, buf46);
  const spec47 = new bsValues.ValueWriter().beginMap().key("tick_count").float(10.0).end().finish()!;
  const buf48 = new Uint8Array(64);
  bsEntities.entityMechanic("physics.projectile_margin", spec47, buf48);
  const spec49 = new bsValues.ValueWriter().beginMap().end().finish()!;
  const buf50 = new Uint8Array(64);
  bsEntities.entityMechanic("nope", spec49, buf50);
  bsEntities.entityRemove(pig);
  bsEntities.entityAlive(pig);
  const buf51 = new Float64Array(3);
  bsEntities.entityPosition(pig, buf51);
  bsEntities.entityRemove(pig);
  bsEntities.entityRemoveUuid("world", "00000000-0000-4000-8000-0000000000ff");
  bsEntities.entityRemoveUuid("world", "nope");
  bsEntities.entityRemove(zombie);
  bsEntities.entityRemove(clone);
  bsEntities.entityRemove(drop);
  bsEntities.entityRelease(me);
  bsEntities.entityRelease(me);
  bsCommands.commandReply(ctx, "tour done");
}

function bad(ctx: bsCore.Ctx): void {
  bsEntities.entityAlive(999);
  bsEntities.entityId(0);
  bsEntities.entityPlayer(-5);
  bsEntities.entityByUuid("");
  bsEntities.entityEventEntity(ctx);
  bsEntities.entityAiAnswer(ctx, 1);
  const buf1 = new Float64Array(3);
  bsEntities.entityPosition(7, buf1);
  const spec2 = new bsValues.ValueWriter().beginMap().end().finish()!;
  const buf3 = new Uint8Array(16);
  bsEntities.entityMechanic("", spec2, buf3);
  bsCommands.commandReply(ctx, "bad done");
}

export function register(): void {
  bsCommands.command("entities tour", "", tour);
  bsCommands.command("entities bad", "", bad);
}
